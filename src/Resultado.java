
/**
 * Enumerado que representa los posibles resultados
 * al finalizar una cita en la clínica veterinaria.
 */
public enum Resultado {

    // La cita se ha realizado correctamente
    ATENDIDA,

    // El paciente no se ha presentado a la cita
    NO_PRESENTADO,

    // La cita ha sido cancelada
    CANCELADA
}

